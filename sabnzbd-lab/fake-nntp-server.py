#!/usr/bin/env python3
"""A minimal fake NNTP server for the SABnzbd lab.

Serves the yEnc bodies generated by make-test-nzb.py on 127.0.0.1:1199.
Implements just enough NNTP for a real SABnzbd download to complete:
greeting, AUTHINFO, CAPABILITIES, GROUP, BODY, HEAD, STAT, QUIT.
Every command received is appended to the log file in argv[2], which
becomes one of the lab transcripts.

Usage: fake-nntp-server.py <segments.json> <logfile>
"""
import json
import socketserver
import sys

SEGMENTS = json.load(open(sys.argv[1]))
LOG = open(sys.argv[2], "a", buffering=1)


class Handler(socketserver.StreamRequestHandler):
    def send(self, text):
        self.wfile.write(text.encode("latin-1"))

    def handle(self):
        self.send("200 lab fake news server ready\r\n")
        LOG.write("--- connection opened ---\n")
        while True:
            raw = self.rfile.readline()
            if not raw:
                break
            line = raw.decode("latin-1").strip()
            LOG.write("C: " + line + "\n")
            parts = line.split(" ", 1)
            cmd = parts[0].upper() if parts else ""
            arg = parts[1] if len(parts) > 1 else ""
            if cmd == "AUTHINFO":
                sub = arg.split(" ", 1)
                if sub[0].upper() == "USER":
                    self.send("381 password required\r\n")
                else:  # PASS
                    self.send("281 authentication accepted\r\n")
            elif cmd == "CAPABILITIES":
                self.send("101 capability list follows\r\n"
                          "VERSION 2\r\nREADER\r\nAUTHINFO USER\r\n.\r\n")
            elif cmd == "MODE":
                self.send("200 reader mode, posting prohibited\r\n")
            elif cmd == "GROUP":
                self.send(f"211 {len(SEGMENTS)} 1 {len(SEGMENTS)} "
                          f"{arg} group selected\r\n")
            elif cmd in ("BODY", "HEAD", "ARTICLE", "STAT"):
                msgid = arg.strip().strip("<>")
                if msgid in SEGMENTS:
                    code = {"BODY": 222, "HEAD": 221,
                            "ARTICLE": 220, "STAT": 223}[cmd]
                    if cmd == "STAT":
                        self.send(f"223 0 <{msgid}> article exists\r\n")
                    else:
                        body = SEGMENTS[msgid]
                        head = ("Subject: labtest payload.bin\r\n"
                                f"Message-ID: <{msgid}>\r\n\r\n")
                        payload = head + body if cmd != "BODY" else body
                        if cmd == "HEAD":
                            payload = head
                        self.send(f"{code} 0 <{msgid}> "
                                  "article retrieved\r\n")
                        self.wfile.write(payload.encode("latin-1"))
                        if not payload.endswith("\r\n"):
                            self.send("\r\n")
                        self.send(".\r\n")
                else:
                    self.send("430 no such article found\r\n")
            elif cmd == "QUIT":
                self.send("205 closing connection\r\n")
                break
            elif cmd == "DATE":
                self.send("111 20260101000000\r\n")
            else:
                self.send("500 command not recognised\r\n")
        LOG.write("--- connection closed ---\n")


class Server(socketserver.ThreadingTCPServer):
    daemon_threads = True
    allow_reuse_address = True


if __name__ == "__main__":
    with Server(("127.0.0.1", 1199), Handler) as srv:
        LOG.write("fake NNTP server listening on 127.0.0.1:1199\n")
        srv.serve_forever()
